-- Run this in Supabase Dashboard -> SQL Editor -> New query.
-- Anonymous Auth is used for the beginner demo: each browser session has a Supabase user ID.
-- Names are profile labels, not secure identity verification. Add real auth before public launch.

create table if not exists public.players (
  player_id uuid primary key references auth.users(id) on delete cascade,
  player_name text not null check (char_length(player_name) between 2 and 24),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  player_id uuid not null references auth.users(id) on delete cascade,
  game_id text not null check (game_id in ('coding-via-gaming', 'pipeline-quest')),
  score integer not null check (score >= 0),
  max_score integer check (max_score is null or max_score > 0),
  detail text not null default 'Completed run' check (char_length(detail) <= 180),
  created_at timestamptz not null default now()
);

create index if not exists game_scores_player_created_idx
  on public.game_scores (player_id, created_at desc);
create index if not exists game_scores_player_game_score_idx
  on public.game_scores (player_id, game_id, score desc);

alter table public.players enable row level security;
alter table public.game_scores enable row level security;

-- A signed-in user (including anonymous auth) can only access their own profile.
drop policy if exists "Players can read own profile" on public.players;
create policy "Players can read own profile"
on public.players for select to authenticated
using (player_id = auth.uid());

drop policy if exists "Players can insert own profile" on public.players;
create policy "Players can insert own profile"
on public.players for insert to authenticated
with check (player_id = auth.uid());

drop policy if exists "Players can update own profile" on public.players;
create policy "Players can update own profile"
on public.players for update to authenticated
using (player_id = auth.uid())
with check (player_id = auth.uid());

drop policy if exists "Players can read own scores" on public.game_scores;
create policy "Players can read own scores"
on public.game_scores for select to authenticated
using (player_id = auth.uid());

drop policy if exists "Players can insert own scores" on public.game_scores;
create policy "Players can insert own scores"
on public.game_scores for insert to authenticated
with check (player_id = auth.uid());

-- No client update/delete policies for score records: scores are append-only from the browser.
-- Important: browser-side scores are still client-generated and can be forged by a determined user.
